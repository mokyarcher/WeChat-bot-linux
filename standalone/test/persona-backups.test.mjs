import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { createPersonaBackups } from '../persona-backups.mjs';
test('persona restore preserves a rollback copy and rejects stale or foreign data', t => {
  const data = mkdtempSync(join(tmpdir(), 'persona-backups-'));
  t.after(() => rmSync(data, { recursive: true, force: true }));
  const roomId = 'bowxt:1@chatroom', filename = 'bowxt_1@chatroom.json';
  const state = text => ({ schema: 1, roomId, energy: 0.7, mood: { valence: 0.5 }, tastes: { likes: [{ text }], dislikes: [] }, diary: [] });
  mkdirSync(join(data, 'persona'));
  const current = join(data, 'persona', filename);
  writeFileSync(current, JSON.stringify(state('现在')));
  const id = '1790000000000-Abc123';
  const directory = join(data, 'persona-backups', id); mkdirSync(directory, { recursive: true });
  writeFileSync(join(directory, filename), JSON.stringify(state('以前')));
  const api = createPersonaBackups(data, roomId);
  const manual = api.create();
  assert.equal(api.preview(manual.id).op, 'persona.manualSnapshot');
  const preview = api.preview(id);
  assert.equal(preview.summary.likes[0], '以前');
  assert.throws(() => api.preview('../persona'), /无效/);
  writeFileSync(current, JSON.stringify(state('已变化')));
  assert.throws(() => api.restore({ id, ...preview }, () => {}), /已变化/);
  const fresh = api.preview(id);
  const result = api.restore(fresh, restored => writeFileSync(current, JSON.stringify(restored)));
  assert.equal(JSON.parse(readFileSync(current)).tastes.likes[0].text, '以前');
  assert.equal(api.preview(result.savedCurrentAs).summary.likes[0], '已变化');
  writeFileSync(join(directory, filename), JSON.stringify({ ...state('其他群'), roomId: 'bowxt:2@chatroom' }));
  assert.throws(() => api.preview(id), /不匹配/);
});
